CREATE DATABASE IF NOT EXISTS pagae CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE pagae;

CREATE TABLE IF NOT EXISTS users (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  email VARCHAR(190) NOT NULL UNIQUE,
  phone VARCHAR(30) NOT NULL DEFAULT '',
  password_hash VARCHAR(255) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS auth_tokens (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  user_id INT UNSIGNED NOT NULL,
  token_hash CHAR(64) NOT NULL UNIQUE,
  expires_at DATETIME NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_auth_tokens_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  INDEX idx_auth_tokens_expiry (expires_at)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS loans (
  id CHAR(36) PRIMARY KEY,
  user_id INT UNSIGNED NOT NULL,
  person_name VARCHAR(120) NOT NULL,
  person_phone VARCHAR(30) NOT NULL DEFAULT '',
  amount DECIMAL(12, 2) NOT NULL,
  description VARCHAR(500) NOT NULL DEFAULT '',
  due_date DATE NOT NULL,
  late_interest_rate DECIMAL(5, 2) NULL,
  created_at DATETIME NOT NULL,
  CONSTRAINT fk_loans_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  INDEX idx_loans_user_created (user_id, created_at)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS loan_payments (
  id CHAR(36) PRIMARY KEY,
  loan_id CHAR(36) NOT NULL,
  amount DECIMAL(12, 2) NOT NULL,
  payment_date DATETIME NOT NULL,
  CONSTRAINT fk_loan_payments_loan FOREIGN KEY (loan_id) REFERENCES loans(id) ON DELETE CASCADE,
  INDEX idx_loan_payments_loan (loan_id)
) ENGINE=InnoDB;
